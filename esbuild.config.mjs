import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the repository: https://github.com/daedalabs/mitos
*/
`;

const prod = process.argv[2] === "production";

// 1. Build Obsidian Plugin Bundle (CJS for Obsidian)
const pluginContext = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

// 2. Build MCP Server Bundle (ESM for Antigravity / Claude Desktop / Cursor)
const mcpContext = await esbuild.context({
  entryPoints: ["src/mcp-server.ts"],
  bundle: true,
  platform: "node",
  target: "node18",
  format: "esm",
  banner: {
    js: "#!/usr/bin/env node\n",
  },
  logLevel: "info",
  treeShaking: true,
  outfile: "scripts/mcp-server.mjs",
});

if (prod) {
  await pluginContext.rebuild();
  await mcpContext.rebuild();
  process.exit(0);
} else {
  await pluginContext.watch();
  await mcpContext.watch();
}
